/** Translation function — returns the translated string for the current locale. */
export function useTranslation() {
  const { locale } = useUIStore();
  const dict = translations[locale] || translations.zh;

  const t = (key: string, params?: Record<string, string | number>): string => {
    let str = dict[key] || translations.zh[key] || key;
    if (params) {
      for (const [k, v] of Object.entries(params)) {
        str = str.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
      }
    }
    return str;
  };

  return t;
}

/** Non-hook version for use outside React components. */
export function translate(key: string, locale: Locale = 'zh', params?: Record<string, string | number>): string {
  const dict = translations[locale] || translations.zh;
  let str = dict[key] || translations.zh[key] || key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      str = str.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
    }
  }
  return str;
}

/** Locale tag for native Intl/Date formatting, derived from the current UI locale. */
export function localeTag(): string {
  return useUIStore.getState().locale === 'en' ? 'en-US' : 'zh-CN';
}
